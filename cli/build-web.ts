// `bun run build:web`: bundles the notebook's script and CodeMirror into
// web/dist/notebook.js, the in-card terminal and xterm.js into web/dist/term.js (+ its
// stylesheet, web/dist/term.css), the board's modules (web/board/) into web/dist/board.js and
// Kaizen Bot's page modules (bot/web/app/) into bot/web/app.js, the Video page's script into web/dist/video.js, all committed, so an install or a checkout serves it with no
// install step and no network. The first line is a hash of what it was built from;
// cli/notes.test.ts fails when a committed file no longer matches.
import { createHash } from "node:crypto";
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";

const root = dirname(import.meta.dir);
const modules = (dir: string) => readdirSync(join(root, dir)).filter((f) => f.endsWith(".ts")).sort().map((f) => `${dir}/${f}`);
// The React layers (web/ui, components, pages, lib) hold .ts and .tsx, in folders of their own; sorted so every OS hashes the same order.
const tree = (dir: string): string[] =>
  readdirSync(join(root, dir), { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : 1))
    .flatMap((e) => (e.isDirectory() ? tree(`${dir}/${e.name}`) : /\.tsx?$/.test(e.name) && !/\.test\.tsx?$/.test(e.name) ? [`${dir}/${e.name}`] : []));
const SOURCES = ["web/notebook/notebook.ts", "web/notebook/notes-lib.ts", "web/notebook/kit.ts", "web/notebook/kit-loader.ts", "web/term/term.ts", "web/video/video.ts", ...modules("web/board"), ...modules("bot/web/app"), ...["ui", "components", "pages", "lib"].flatMap((d) => tree(`web/${d}`)), "web/ui/theme.css"];
export const OUT = join(root, "web", "dist", "notebook.js");
export const TERM_OUT = join(root, "web", "dist", "term.js");
export const BOARD_OUT = join(root, "web", "dist", "board.js");
export const BOT_OUT = join(root, "bot", "web", "app.js");
export const KIT_OUT = join(root, "web", "dist", "notebook-kit.js");
export const VIDEO_OUT = join(root, "web", "dist", "video.js");
export const UI_CSS_OUT = join(root, "web", "dist", "ui.css");

// The sources and the exact dependency versions: a CodeMirror bump is a rebuild too.
export function sourceHash() {
  const h = createHash("sha256");
  for (const f of SOURCES) h.update(readFileSync(join(root, f), "utf8").replace(/\r\n/g, "\n"));
  h.update(JSON.stringify(JSON.parse(readFileSync(join(root, "package.json"), "utf8")).devDependencies ?? {}));
  return h.digest("hex").slice(0, 16);
}
export const banner = (what = "notebook", from = "web/notebook/notebook.ts") => `/* kaizen ${what} ${sourceHash()} -- generated by bun run build:web from ${from}; do not edit */`;

if (import.meta.main) {
  const bundles = [
    ["web/notebook/notebook.ts", OUT, "notebook"],
    ["web/notebook/kit.ts", KIT_OUT, "notebook kit"],
    ["web/term/term.ts", TERM_OUT, "terminal"],
    ["web/board/main.ts", BOARD_OUT, "board"],
    ["bot/web/app/main.ts", BOT_OUT, "bot page"],
    ["web/video/video.ts", VIDEO_OUT, "video page"],
  ] as const;
  for (const [src, out, what] of bundles) {
    // The terminal, the board and the bot page are classic scripts: wrapped, or their
    // top-level names collide with each other's globals and the whole file is refused.
    // React reads process.env.NODE_ENV: without this the board carries React's development build (twice the size, slower).
    const define = what === "board" || what === "notebook kit" ? { "process.env.NODE_ENV": '"production"' } : undefined;
    const r = await Bun.build({ entrypoints: [join(root, src)], target: "browser", minify: true, format: what === "notebook" ? "esm" : "iife", define });
    if (!r.success) { for (const l of r.logs) console.error(l); process.exit(1); }
    writeFileSync(out, banner(what, src) + "\n" + await r.outputs[0]!.text());
    console.log(`  ${out.slice(root.length + 1)}  ${(Bun.file(out).size / 1024).toFixed(0)} KB`);
  }
  copyFileSync(join(root, "node_modules", "@xterm", "xterm", "css", "xterm.css"), join(root, "web", "dist", "term.css"));
  // The board's Tailwind: web/ui/theme.css scans web/ui, components, pages and lib for the classes they use.
  const tw = Bun.spawnSync([process.execPath, join(root, "node_modules", "@tailwindcss", "cli", "dist", "index.mjs"), "-i", join(root, "web", "ui", "theme.css"), "-o", UI_CSS_OUT, "--minify"], { cwd: root, stdout: "pipe", stderr: "pipe" });
  if (tw.exitCode !== 0) { console.error(tw.stderr.toString()); process.exit(1); }
  const css = readFileSync(UI_CSS_OUT, "utf8");
  writeFileSync(UI_CSS_OUT, `/* kaizen ui ${sourceHash()} -- generated by bun run build:web from web/ui/theme.css; do not edit */\n` + css);
  console.log(`  web/dist/ui.css  ${(Bun.file(UI_CSS_OUT).size / 1024).toFixed(0)} KB`);
}
